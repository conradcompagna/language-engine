print("Running CAMeL Tools morphological segmentation ...")
from camel_tools_arabic_tokenizer import (
    _get_camel_tools_bundle, _iter_sentence_chunks, _normalize_morph_token,
)
bundle = _get_camel_tools_bundle()
camel_results = []
for chunk in _iter_sentence_chunks(TEXT):
    for bt in list(bundle.simple_word_tokenize(chunk) or []):
        raw = list(bundle.morph_tokenizer.tokenize([bt]) or [])
        segs = [_normalize_morph_token(t) for t in raw]
        segs = [s for s in segs if s]
        camel_results.append({"word": bt, "morph_segments": segs or [bt]})

print("Running Trankit (native Arabic tokenizer + MWT) ...")
from language_registry import init_trankit, run_trankit
init_trankit()
doc = run_trankit(TEXT, "ar")
trankit_results = []
for sent in doc.get("sentences", []):
    for tok in sent.get("tokens", []):
        e = {"text": tok.get("text", ""), "upos": tok.get("upos", ""), "lemma": tok.get("lemma", "")}
        if "expanded" in tok:
            e["expanded"] = tok["expanded"]
        trankit_results.append(e)

